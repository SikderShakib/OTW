const ROLES = ['founder', 'president', 'vp', 'gs', 'jgs', 'treasurer', 'org', 'office', 'publicity', 'sports', 'cultural', 'advisor', 'member'];
const INCOME_CATEGORIES = ['subscription', 'donation', 'event_income', 'other_income'];
const EXPENSE_CATEGORIES = ['office', 'event', 'printing', 'transport', 'welfare', 'other_expense'];

let currentLang = 'bn';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.bn[key] || key;
}
function roleName(role) { return t('role_' + role); }
function catName(cat) { return t('cat_' + cat); }

/* Apply translations to all static elements */
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.documentElement.lang = currentLang;
  document.getElementById('langBn').classList.toggle('active', currentLang === 'bn');
  document.getElementById('langEn').classList.toggle('active', currentLang === 'en');
}

function setLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'bn';
  db.settings.lang = currentLang;
  saveDB();
  applyI18n();
  applyOrgBranding();
  buildStaticSelects();
  renderCurrentPage();
  updateSidebarStats();
  updateHeaderDate();
  if (typeof window !== 'undefined' && window.OTWCloud && window.OTWCloud.refreshUI) {
    try { window.OTWCloud.refreshUI(); } catch (e) {}
  }
}
